    public static boolean supports(String kind){return DOCUMENTS.containsKey(kind);}
    public static Document get(String kind){return DOCUMENTS.get(kind);}
    public static Collection<Document> all(){return DOCUMENTS.values();}
    public static String categoryName(String category){return switch(category){case "townsfolk"->"镇民";case "outsider"->"外来者";case "minion"->"爪牙";case "demon"->"恶魔";default->category;};}
    private static Section section(String id,String title,String category,String summary,String... paragraphs){return new Section(id,title,category,"",summary,List.of(paragraphs));}
    private static Document script(){
        List<Section> sections=new ArrayList<>();
        for(var role:RoleCatalog.all()) {
            boolean good=role.type().equals("townsfolk")||role.type().equals("outsider");
            sections.add(new Section(role.id(),role.name(),categoryName(role.type()),good?"good":"evil",role.ability(),List.of()));
        }
        return new Document("script_card","暗流涌动 · 角色技能",sections);
    }
